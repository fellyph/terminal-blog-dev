const fs = require( 'node:fs/promises' );
const path = require( 'node:path' );
const postcss = require( 'postcss' );
const cssnano = require( 'cssnano' );

const directory = path.resolve( __dirname, '../assets/css' );
const names = [ 'colors', 'custom', 'footer-art', 'menu-pixels' ];
const check = process.argv.includes( '--check' );

async function build() {
	for ( const name of names ) {
		const from = path.join( directory, `${ name }.css` );
		const to = path.join( directory, `${ name }.min.css` );
		const source = await fs.readFile( from, 'utf8' );
		const result = await postcss( [ cssnano( {
			preset: [ 'default', { normalizeUrl: false } ],
		} ) ] ).process( source, { from, to, map: false } );
		const output = `/* Generated by npm run build:css. Edit ${ name }.css. */\n${ result.css }\n`;
		if ( check ) {
			const current = await fs.readFile( to, 'utf8' ).catch( () => '' );
			if ( current !== output ) {
				throw new Error( `${ name }.min.css is stale. Run npm run build:css.` );
			}
		} else {
			await fs.writeFile( to, output );
		}
		console.log( `${ name }: ${ Buffer.byteLength( source ) } → ${ Buffer.byteLength( output ) } bytes${ check ? ' (verified)' : '' }` );
	}
}

build().catch( ( error ) => {
	console.error( error.message );
	process.exitCode = 1;
} );
